#!/usr/bin/env python3
"""Liberty for the antenna diode cells of a library that ships none (7-track ANT2/ANT4).

Usage: antenna_liberty.py <lib.cdl> <cells.lef> <dio.mdl> <libname> <out.lib>

The cells are the subcircuits of the CDL that contain only junction diodes (D elements) and
have one signal pin besides the supplies. Their only electrical property for STA is the input
capacitance, computed as the zero-bias junction capacitance of the diodes,
    C = sum m * (CJ * AREA + CJSW * PJ)
with CJ / CJSW of the diode models in the ngspice model file (corner independent: the
statistical / corner deltas of the model are left at zero). Area comes from the LEF SIZE.
"""

import re
import sys

SUPPLIES = {'VDD', 'VSS', 'VNW', 'VPW', 'VDDIO', 'VSSIO'}


def num(v):
    m = re.match(r"^'?([-+]?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?)", v)
    x = float(m.group(1))
    suf = v[m.end(1):].lower().strip("'")
    for s, f in (('meg', 1e6), ('u', 1e-6), ('n', 1e-9), ('p', 1e-12), ('f', 1e-15), ('m', 1e-3)):
        if suf.startswith(s):
            return x * f
    return x


def models(path):
    """{model: (cj F/m2, cjsw F/m)}"""
    out = {}
    cur = None
    for line in open(path, encoding='latin-1'):
        m = re.match(r'\s*\.model\s+(\S+)\s+d\b', line, re.I)
        if m:
            cur = m.group(1).lower()
            out[cur] = [0.0, 0.0]
            continue
        if cur and line.strip().startswith('+'):
            for k, v in re.findall(r"(\w+)\s*=\s*('[^']*'|\S+)", line):
                if k.lower() == 'cj':
                    out[cur][0] = num(v)
                elif k.lower() == 'cjsw':
                    out[cur][1] = num(v)
        elif line.strip() and not line.strip().startswith('*'):
            cur = None
    return out


def diode_cells(cdl):
    cells = {}
    name = pins = None
    devs = []
    for line in open(cdl, encoding='latin-1'):
        t = line.split()
        if not t:
            continue
        if t[0].upper() == '.SUBCKT':
            name, pins, devs, ok = t[1], t[2:], [], True
            continue
        if name and t[0].upper() == '.ENDS':
            sig = [p for p in pins if p.upper() not in SUPPLIES]
            if devs and len(sig) == 1 and all(d is not None for d in devs):
                cells[name] = (sig[0], devs)
            name = None
            continue
        if name and t[0][0] in '*':
            continue
        if name:
            if t[0][0] in 'Dd':
                p = {k.lower(): v for k, v in (x.split('=', 1) for x in t[4:] if '=' in x)}
                devs.append((t[3].lower(), num(p.get('area', '0')), num(p.get('pj', '0')),
                             num(p.get('m', '1'))))
            else:
                devs.append(None)
    return cells


def lef_sizes(lef):
    out = {}
    macro = None
    for line in open(lef):
        t = line.split()
        if t[:1] == ['MACRO']:
            macro = t[1]
        elif t[:1] == ['SIZE'] and macro:
            out[macro] = float(t[1]) * float(t[3])
    return out


def main():
    cdl, lef, mdl, libname, out = sys.argv[1:6]
    mod = models(mdl)
    size = lef_sizes(lef)
    cells = diode_cells(cdl)
    o = ['/* GENERATED by hacking/antenna_liberty.py: antenna diode cells of %s.' % libname,
         ' * Input capacitance = zero-bias junction capacitance of the diodes (CDL areas,',
         ' * CJ / CJSW of %s); no timing arcs, corner independent. */' % mdl.split('/')[-1],
         'library (%s_antenna) {' % libname,
         '  delay_model : table_lookup;',
         '  capacitive_load_unit (1,pf);',
         '  current_unit : "1mA";',
         '  leakage_power_unit : "1nW";',
         '  pulling_resistance_unit : "1kohm";',
         '  time_unit : "1ns";',
         '  voltage_unit : "1V";',
         '  voltage_map (VDD, 1.2);',
         '  voltage_map (VSS, 0);',
         '  default_cell_leakage_power : 0;',
         '  nom_process : 1;',
         '  nom_temperature : 25;',
         '  nom_voltage : 1.2;']
    for name in sorted(cells):
        pin, devs = cells[name]
        c = 0.0
        for model, a, pj, m in devs:
            cj, cjsw = mod[model]
            c += m * (cj * a + cjsw * pj)
        o += ['  cell (%s) {' % name,
              '    area : %g;' % size.get(name, 0.0),
              '    cell_footprint : "ANTENNA";',
              '    dont_touch : true;',
              '    cell_leakage_power : 0;',
              '    pg_pin (VDD) {', '      pg_type : primary_power;', '      voltage_name : "VDD";', '    }',
              '    pg_pin (VSS) {', '      pg_type : primary_ground;', '      voltage_name : "VSS";', '    }',
              '    pin (%s) {' % pin,
              '      direction : input;',
              '      related_power_pin : "VDD";',
              '      related_ground_pin : "VSS";',
              '      capacitance : %.6g;' % (c * 1e12),
              '    }', '  }']
        print('antenna_liberty: %s pin %s C = %.3f fF' % (name, pin, c * 1e15), file=sys.stderr)
    o.append('}')
    open(out, 'w').write('\n'.join(o) + '\n')


if __name__ == '__main__':
    main()
